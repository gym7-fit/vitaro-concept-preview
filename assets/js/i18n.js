function applyLang(lang){
  if(!translations[lang]) lang = 'en';
  document.querySelectorAll('[data-i18n]').forEach(function(el){
    var key = el.getAttribute('data-i18n');
    var val = translations[lang][key];
    if(val !== undefined){ el.textContent = val; }
  });
  document.documentElement.setAttribute('lang', lang);
  var titleKey = document.body.getAttribute('data-title-key') || 'meta.title';
  var titleVal = translations[lang][titleKey];
  if(titleVal){ document.title = titleVal; }
  var sel = document.getElementById('langSelect');
  if(sel){ sel.value = lang; }
  try{ localStorage.setItem('vitaro-lang', lang); }catch(e){}
}

function detectLang(){
  try{
    var stored = localStorage.getItem('vitaro-lang');
    if(stored && translations[stored]) return stored;
  }catch(e){}
  var nav = ((navigator.language || navigator.userLanguage || 'en') + '').toLowerCase();
  if(nav.indexOf('de') === 0) return 'de';
  if(nav.indexOf('es') === 0) return 'es';
  return 'en';
}

applyLang(detectLang());
